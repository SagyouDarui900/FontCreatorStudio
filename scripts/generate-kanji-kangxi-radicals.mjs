#!/usr/bin/env node
/**
 * Generate src/data/kanjiKangxiRadicals.ts: Kangxi radical number (1-214)
 * for every JIS X 0208 level 1 / level 2 kanji, from the Unicode Unihan
 * database (kRSUnicode field, first value = primary radical).
 *
 * Usage:
 *   node scripts/generate-kanji-kangxi-radicals.mjs <path-to-Unihan_IRGSources.txt>
 *
 * Get the input from https://www.unicode.org/Public/UNIDATA/Unihan.zip
 * (extract Unihan_IRGSources.txt). Unicode 18.0.0 was used for the
 * committed data file; a newer Unihan release should give the same
 * assignments for these kanji, but re-run the spot checks if it changes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const irgSourcesPath = process.argv[2];
if (!irgSourcesPath) {
  console.error('Usage: node scripts/generate-kanji-kangxi-radicals.mjs <path-to-Unihan_IRGSources.txt>');
  process.exit(2);
}

function extractKanjiList(relativePath) {
  const text = readFileSync(path.join(repoRoot, relativePath), 'utf8');
  return [...text.matchAll(/"([^"]+)"/g)].map((m) => m[1]);
}

const jisKanji = [
  ...extractKanjiList('src/data/jisLevel1.ts'),
  ...extractKanjiList('src/data/jisLevel2.ts'),
];
const uniqueJis = [...new Set(jisKanji)];

const rsUnicode = new Map();
for (const line of readFileSync(irgSourcesPath, 'utf8').split('\n')) {
  if (!line.startsWith('U+') || !line.includes('\tkRSUnicode\t')) continue;
  const [codePart, , value] = line.split('\t');
  const cp = parseInt(codePart.slice(2), 16);
  const first = value.trim().split(/\s+/)[0].replace(/'/g, '');
  const radical = parseInt(first.split('.')[0], 10);
  if (Number.isFinite(radical) && radical >= 1 && radical <= 214) {
    rsUnicode.set(cp, radical);
  }
}

const mapping = new Map();
const unmapped = [];
for (const ch of uniqueJis) {
  const radical = rsUnicode.get(ch.codePointAt(0));
  if (radical === undefined) unmapped.push(ch);
  else mapping.set(ch, radical);
}
if (unmapped.length > 0) {
  console.error(`Unmapped kanji (${unmapped.length}): ${unmapped.join(' ')}`);
  process.exit(1);
}

// Spot checks against the Kangxi dictionary assignments.
const spotChecks = [
  ['休', 9], ['海', 85], ['林', 75], ['明', 72], ['語', 149],
  ['金', 167], ['亜', 7], ['一', 1], ['国', 31], ['花', 140],
  ['山', 46], ['川', 47], ['雨', 173], ['電', 173], ['車', 159],
  ['食', 184], ['馬', 187], ['魚', 195], ['鳥', 196], ['黒', 203],
  ['愛', 61], ['圧', 32], ['安', 40], ['案', 75], ['引', 57],
];
for (const [ch, expected] of spotChecks) {
  if (mapping.get(ch) !== expected) {
    console.error(`Spot check failed: ${ch} expected radical ${expected}, got ${mapping.get(ch)}`);
    process.exit(1);
  }
}

const entries = uniqueJis.map((ch) => `  '${ch}': ${mapping.get(ch)},`);
const header = `/**
 * Kangxi radical number (1-214) for every JIS X 0208 level 1 / level 2 kanji
 * (${uniqueJis.length.toLocaleString('en-US')} kanji).
 *
 * Generated by scripts/generate-kanji-kangxi-radicals.mjs from the Unicode
 * Unihan database (Unihan_IRGSources.txt, kRSUnicode field; the first value
 * is the primary radical, a trailing apostrophe marks a simplified variant
 * and is ignored). The committed file used Unihan 18.0.0 (2026-07-31).
 * Do not edit by hand; re-run the generator instead.
 */
`;
const body = `export const KANGXI_RADICAL_BY_KANJI: Record<string, number> = {
${entries.join('\n')}
};

/** Kangxi radical number (1-214) for a JIS level 1 / level 2 kanji, or undefined. */
export function getKangxiRadicalForKanji(char: string): number | undefined {
  return KANGXI_RADICAL_BY_KANJI[char];
}
`;

writeFileSync(path.join(repoRoot, 'src/data/kanjiKangxiRadicals.ts'), header + body);
console.log(`Wrote src/data/kanjiKangxiRadicals.ts (${uniqueJis.length} kanji, ${new Set(mapping.values()).size} radicals used)`);
