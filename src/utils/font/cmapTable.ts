export interface CmapFormat14Mapping {
  baseUnicode: number;
  selectorCode: number;
  glyphIndex: number;
}

const SFNT_HEADER_SIZE = 12;
const TABLE_RECORD_SIZE = 16;

function writeUint24(view: DataView, offset: number, value: number): void {
  view.setUint8(offset, (value >>> 16) & 0xff);
  view.setUint8(offset + 1, (value >>> 8) & 0xff);
  view.setUint8(offset + 2, value & 0xff);
}

/**
 * Extract the raw bytes of an SFNT table (e.g. 'cmap') from a compiled OTF/TTF buffer.
 */
export function extractSfntTableBytes(buffer: ArrayBuffer, targetTag: string): Uint8Array | null {
  const bytes = new Uint8Array(buffer);
  const view = new DataView(buffer);
  if (bytes.length < SFNT_HEADER_SIZE) return null;

  const numTables = view.getUint16(4, false);
  if (bytes.length < SFNT_HEADER_SIZE + numTables * TABLE_RECORD_SIZE) return null;

  for (let i = 0; i < numTables; i++) {
    const recOffset = SFNT_HEADER_SIZE + i * TABLE_RECORD_SIZE;
    const tag = String.fromCharCode(
      bytes[recOffset],
      bytes[recOffset + 1],
      bytes[recOffset + 2],
      bytes[recOffset + 3]
    );
    if (tag !== targetTag) continue;

    const offset = view.getUint32(recOffset + 8, false);
    const length = view.getUint32(recOffset + 12, false);
    if (offset + length > bytes.length) return null;
    return bytes.slice(offset, offset + length);
  }
  return null;
}

/**
 * Build an OpenType `cmap` Format 14 (Unicode Variation Sequences) subtable.
 * Returns null if no valid mappings are provided.
 */
export function buildCmapFormat14Subtable(mappings: CmapFormat14Mapping[]): Uint8Array | null {
  if (!mappings || mappings.length === 0) return null;

  const bySelector = new Map<number, Map<number, number>>();
  for (const m of mappings) {
    const base = Math.round(m.baseUnicode);
    const sel = Math.round(m.selectorCode);
    const gid = Math.round(m.glyphIndex);
    if (
      !Number.isInteger(base) ||
      base <= 0 ||
      base > 0x10ffff ||
      (base >= 0xd800 && base <= 0xdfff)
    ) {
      continue;
    }
    if (
      !Number.isInteger(sel) ||
      sel <= 0 ||
      sel > 0x10ffff ||
      (sel >= 0xd800 && sel <= 0xdfff)
    ) {
      continue;
    }
    if (!Number.isInteger(gid) || gid <= 0 || gid > 0xffff) {
      continue;
    }
    let inner = bySelector.get(sel);
    if (!inner) {
      inner = new Map<number, number>();
      bySelector.set(sel, inner);
    }
    inner.set(base, gid);
  }

  if (bySelector.size === 0) return null;

  const sortedSelectors = Array.from(bySelector.keys()).sort((a, b) => a - b);
  const numSelectors = sortedSelectors.length;

  const groupedRecords = sortedSelectors.map((sel) => {
    const entries = Array.from(bySelector.get(sel)!.entries())
      .sort((a, b) => a[0] - b[0])
      .map(([unicodeValue, glyphID]) => ({ unicodeValue, glyphID }));
    return { selectorCode: sel, entries };
  });

  // Format 14 header: format(2) + length(4) + numVarSelectorRecords(4) = 10 bytes
  // Each VariationSelectorRecord: varSelector(3) + defaultUVSOffset(4) + nonDefaultUVSOffset(4) = 11 bytes
  const headerAndRecordsSize = 10 + numSelectors * 11;
  let totalLength = headerAndRecordsSize;
  const nonDefaultOffsets: number[] = [];

  for (const group of groupedRecords) {
    nonDefaultOffsets.push(totalLength);
    // NonDefaultUVS: numUVSMappings(4) + count * (unicodeValue(3) + glyphID(2))
    totalLength += 4 + group.entries.length * 5;
  }

  const out = new Uint8Array(totalLength);
  const view = new DataView(out.buffer);

  view.setUint16(0, 14, false); // format = 14
  view.setUint32(2, totalLength, false); // length
  view.setUint32(6, numSelectors, false); // numVarSelectorRecords

  let recOffset = 10;
  for (let i = 0; i < groupedRecords.length; i++) {
    const group = groupedRecords[i];
    writeUint24(view, recOffset, group.selectorCode);
    view.setUint32(recOffset + 3, 0, false); // defaultUVSOffset = 0 (all mapped to explicit variant glyphs)
    view.setUint32(recOffset + 7, nonDefaultOffsets[i], false);
    recOffset += 11;
  }

  for (let i = 0; i < groupedRecords.length; i++) {
    const group = groupedRecords[i];
    let tableOffset = nonDefaultOffsets[i];
    view.setUint32(tableOffset, group.entries.length, false);
    tableOffset += 4;
    for (const entry of group.entries) {
      writeUint24(view, tableOffset, entry.unicodeValue);
      view.setUint16(tableOffset + 3, entry.glyphID, false);
      tableOffset += 5;
    }
  }

  return out;
}

/**
 * Splice an existing OpenType `cmap` table to add (or replace) a Format 14 subtable
 * under Platform ID = 0 (Unicode), Encoding ID = 5 (Unicode Variation Sequences).
 *
 * Existing Format 4 / Format 12 subtables generated by opentype.js do not embed offsets
 * relative to the start of the `cmap` table, so shifting the encoding record offsets
 * by the encoding directory size delta keeps them completely valid.
 */
export function spliceCmapWithFormat14(
  existingCmapBytes: Uint8Array,
  mappings: CmapFormat14Mapping[]
): Uint8Array {
  const format14Bytes = buildCmapFormat14Subtable(mappings);
  if (!format14Bytes) return existingCmapBytes;

  if (existingCmapBytes.length < 4) {
    throw new Error('Invalid cmap table: too short');
  }
  const srcView = new DataView(
    existingCmapBytes.buffer,
    existingCmapBytes.byteOffset,
    existingCmapBytes.byteLength
  );
  const version = srcView.getUint16(0, false);
  const origNumTables = srcView.getUint16(2, false);
  const origDirEnd = 4 + origNumTables * 8;
  if (existingCmapBytes.length < origDirEnd) {
    throw new Error('Invalid cmap table: truncated encoding records');
  }

  const keptRecords: { platformID: number; encodingID: number; subtableOffset: number }[] = [];
  for (let i = 0; i < origNumTables; i++) {
    const off = 4 + i * 8;
    const platformID = srcView.getUint16(off, false);
    const encodingID = srcView.getUint16(off + 2, false);
    const subtableOffset = srcView.getUint32(off + 4, false);
    if (platformID === 0 && encodingID === 5) {
      continue;
    }
    keptRecords.push({ platformID, encodingID, subtableOffset });
  }

  const nextNumTables = keptRecords.length + 1;
  const nextDirEnd = 4 + nextNumTables * 8;
  const headerDelta = nextDirEnd - origDirEnd;
  const existingSubtablesBody = existingCmapBytes.subarray(origDirEnd);
  const format14Offset = nextDirEnd + existingSubtablesBody.length;
  const totalLength = format14Offset + format14Bytes.length;

  const allRecords = [
    ...keptRecords.map((r) => ({
      platformID: r.platformID,
      encodingID: r.encodingID,
      subtableOffset: r.subtableOffset + headerDelta,
    })),
    {
      platformID: 0,
      encodingID: 5,
      subtableOffset: format14Offset,
    },
  ].sort((a, b) =>
    a.platformID !== b.platformID ? a.platformID - b.platformID : a.encodingID - b.encodingID
  );

  const out = new Uint8Array(totalLength);
  const outView = new DataView(out.buffer);
  outView.setUint16(0, version, false);
  outView.setUint16(2, nextNumTables, false);

  let recOff = 4;
  for (const rec of allRecords) {
    outView.setUint16(recOff, rec.platformID, false);
    outView.setUint16(recOff + 2, rec.encodingID, false);
    outView.setUint32(recOff + 4, rec.subtableOffset, false);
    recOff += 8;
  }

  out.set(existingSubtablesBody, nextDirEnd);
  out.set(format14Bytes, format14Offset);

  return out;
}
